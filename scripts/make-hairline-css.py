"""
make-hairline-css.py — the mechanical half of the hairline finish.

`static/hairline.css` draws the cockpit in the getpantheon.ai material when
`<html data-ck-finish="hairline">` (theme editor → Finish). Most of it is
written by hand: tokens, the flush shell, the composer, links, tabs. The rest
is the same four edits applied to every rule in `static/cockpit.css` (and
the device-control tail of `static/style.css`) that carries the glass recipe, and writing those out by hand would go stale the
first time someone adds a pill to the cockpit. So this script reads
`static/cockpit.css` and writes them between the two marker comments at the
end of `static/hairline.css`:

  * radii: a pill (999px) becomes a 6px corner, and a rounded corner tightens
    (9-12px → 6px, 13-16px → 8px, 17px and up → 10px); circles (50%) and the
    few pills that are a track or a count stay round;
  * accent gradients (`--ck-accent` → `--ck-accent-2`) become the flat accent;
  * accent glows (`--ck-accent-glow` in a shadow) go;
  * backdrop blurs go (hairline surfaces are solid, so a blur only costs).

Each emitted rule keeps the source's at-rule wrapper and `!important`, and its
selector gains `[data-ck-finish="hairline"]`, so it out-ranks the rule it
answers by exactly one attribute.

Usage:
    python3 scripts/make-hairline-css.py          rewrite the generated block
    python3 scripts/make-hairline-css.py --check  exit 1 if it is out of date
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
COCKPIT = ROOT / "static" / "cockpit.css"
STYLE = ROOT / "static" / "style.css"
# style.css is read from here on: the device controls (`.ctl-*`), the phone's
# and workstation's bars and Apollo's pane and orb, the one part of that sheet
# drawn in the cockpit's pill-and-glass language without the cockpit's prefix.
STYLE_FROM = "/* ── `PHW-CTL` · the device controls: one language for the phone, the"
HAIRLINE = ROOT / "static" / "hairline.css"
BEGIN = "/* ── generated by scripts/make-hairline-css.py — begin (do not edit by hand) ── */"
END = "/* ── generated by scripts/make-hairline-css.py — end ── */"
SCOPE = '[data-ck-finish="hairline"]'

# Pills that are a track, a meter or a count, not a control: they stay round.
KEEP_ROUND = re.compile(r"scrollbar|progress|range|slider-runnable|range-track|#ck-resizer|\.n\b|reaction-badge|\.ctl-switch\b")


def strip_comments(css: str) -> str:
    return re.sub(r"/\*.*?\*/", "", css, flags=re.S)


def walk(css: str, wrappers=()):
    """Yield (wrappers, selector, body) for every style rule, at-rules unwrapped."""
    i, n = 0, len(css)
    while i < n:
        j = css.find("{", i)
        if j < 0:
            return
        head = css[i:j].strip()
        depth, k = 1, j + 1
        while depth and k < n:
            if css[k] == "{":
                depth += 1
            elif css[k] == "}":
                depth -= 1
            k += 1
        body = css[j + 1:k - 1]
        if head.startswith(("@media", "@supports", "@container")):
            yield from walk(body, wrappers + (" ".join(head.split()),))
        elif head.startswith("@") or head.startswith(("from", "to")) or re.match(r"^[\d.]+%", head):
            pass  # keyframes, font-face, and their steps
        elif head:
            yield wrappers, " ".join(head.split()), body
        i = k


def split_top(s: str, sep: str = ",") -> list[str]:
    out, depth, cur = [], 0, ""
    for ch in s:
        if ch in "([":
            depth += 1
        elif ch in ")]":
            depth -= 1
        if ch == sep and depth == 0:
            out.append(cur)
            cur = ""
        else:
            cur += ch
    out.append(cur)
    return [p.strip() for p in out if p.strip()]


def declarations(body: str) -> list[tuple[str, str, bool]]:
    out = []
    for part in split_top(body, ";"):
        if ":" not in part:
            continue
        prop, val = part.split(":", 1)
        prop, val = prop.strip().lower(), val.strip()
        imp = bool(re.search(r"!\s*important\s*$", val))
        val = re.sub(r"\s*!\s*important\s*$", "", val)
        out.append((prop, val, imp))
    return out


def scoped(selector: str) -> str:
    parts = []
    for sel in split_top(selector):
        if sel.startswith("html.cockpit"):
            parts.append("html.cockpit" + SCOPE + sel[len("html.cockpit"):])
        elif sel.startswith(":root"):
            parts.append(":root" + SCOPE + sel[len(":root"):])
        else:
            parts.append("html.cockpit" + SCOPE + " " + sel)
    return ", ".join(parts)


def tighten(px: float) -> str:
    if px <= 8:
        return f"{px:g}px"
    if px >= 999:
        return "6px"
    if px <= 12:
        return "6px"
    if px <= 16:
        return "8px"
    return "10px"


def new_radius(selector: str, val: str) -> str | None:
    if "var(" in val or "%" in val or "calc(" in val:
        return None
    if "999px" in val and KEEP_ROUND.search(selector):
        return None
    nums = re.findall(r"([\d.]+)px", val)
    if not nums or all(float(x) <= 8 for x in nums):
        return None
    out = re.sub(r"([\d.]+)px", lambda m: tighten(float(m.group(1))), val)
    return out if out != val else None


ACCENT_GRADIENT = re.compile(r"linear-gradient\([^;]*var\(--ck-accent\)[^;]*var\(--ck-accent-2\)[^;]*\)")


def edits(selector: str, body: str) -> list[str]:
    out = []
    for prop, val, imp in declarations(body):
        bang = " !important" if imp else ""
        if prop == "border-radius":
            r = new_radius(selector, val)
            if r:
                out.append(f"border-radius: {r}{bang}")
        elif prop in ("background", "background-image") and ACCENT_GRADIENT.search(val) \
                and "background-clip" not in body and "-webkit-background-clip" not in body:
            out.append(f"background: var(--ck-accent){bang}")
        elif prop == "box-shadow" and "--ck-accent-glow" in val:
            out.append(f"box-shadow: none{bang}")
        elif prop in ("backdrop-filter", "-webkit-backdrop-filter") and val != "none":
            out.append(f"{prop}: none{bang}")
    # one of each property, last wins, as in the source
    seen, uniq = set(), []
    for d in reversed(out):
        p = d.split(":", 1)[0]
        if p not in seen:
            seen.add(p)
            uniq.append(d)
    return list(reversed(uniq))


def sources() -> list[str]:
    style = STYLE.read_text(encoding="utf-8")
    at = style.find(STYLE_FROM)
    if at < 0:
        raise SystemExit(f"{STYLE}: the marker this script reads from is gone: {STYLE_FROM!r}")
    return [strip_comments(COCKPIT.read_text(encoding="utf-8")), strip_comments(style[at:])]


def generate() -> str:
    lines = []
    for wrappers, selector, body in (r for css in sources() for r in walk(css)):
        if "::-webkit-scrollbar" in selector or "::-moz-range" in selector or "::-webkit-slider" in selector:
            continue
        ds = edits(selector, body)
        if not ds:
            continue
        rule = f"{scoped(selector)} {{ {'; '.join(ds)}; }}"
        for w in reversed(wrappers):
            rule = f"{w} {{ {rule} }}"
        lines.append(rule)
    return "\n".join(lines)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    src = HAIRLINE.read_text(encoding="utf-8")
    if BEGIN not in src or END not in src:
        print(f"{HAIRLINE}: the generated block's markers are missing", file=sys.stderr)
        return 2
    head, rest = src.split(BEGIN, 1)
    _, tail = rest.split(END, 1)
    out = f"{head}{BEGIN}\n{generate()}\n{END}{tail}"
    if args.check:
        if out != src:
            print("static/hairline.css is out of date: run python3 scripts/make-hairline-css.py", file=sys.stderr)
            return 1
        return 0
    HAIRLINE.write_text(out, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())

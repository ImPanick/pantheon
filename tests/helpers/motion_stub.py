"""One `motion.js` stub for every JS sandbox, derived from the real module.

Four test files built their own, each a single line exporting
`prefersReducedMotion` and nothing else. `P1-15` added a second export to
`static/js/motion.js` and gave `ui.js` an `import { prefersReducedMotion,
scrollBehavior }` — and every sandbox serving one of those stubs died with

    SyntaxError: The requested module './motion.js' does not provide an
    export named 'scrollBehavior'

sixteen cases in one file. The stubs were right about what they needed and
wrong about what the module *has*, and nothing could tell them apart.

So the names are read out of the real file and every one of them is exported.
`reduced=True` flips the preference; everything else answers the way a browser
with no preference set does. Deriving rather than listing means the next export
added to `motion.js` appears here the same day, which is the whole point —
a hand-maintained stub is a fifth copy of the module's surface (`Law 7`).
"""

from __future__ import annotations

import re
from pathlib import Path

_MOTION = Path(__file__).resolve().parents[2] / "static" / "js" / "motion.js"

#: What each export answers in a sandbox. A name absent from here still gets a
#: stub — a no-op returning `undefined` — so a new export cannot break a
#: sandbox; it just does nothing until someone decides what it should do.
_ANSWERS = {
    "prefersReducedMotion": ("false", "true"),
    "scrollBehavior": ("'smooth'", "'auto'"),
    "onMotionPreferenceChange": ("() => {}", "() => {}"),
}


def motion_exports() -> tuple:
    """Every function `static/js/motion.js` exports, in source order."""
    src = _MOTION.read_text(encoding="utf-8")
    return tuple(re.findall(r"^export function (\w+)\s*\(", src, re.M))


def motion_stub(*, reduced: bool = False) -> str:
    """A `motion.js` whose exports match the real module's, name for name."""
    names = motion_exports()
    assert "prefersReducedMotion" in names, (
        "motion.js no longer exports prefersReducedMotion; the stub is reading "
        "the wrong file or the module was renamed")
    lines = ["// Generated by tests/helpers/motion_stub.py from static/js/motion.js."]
    for name in names:
        answer = _ANSWERS.get(name, ("undefined", "undefined"))[1 if reduced else 0]
        lines.append(f"export function {name}() {{ return {answer}; }}")
    return "\n".join(lines) + "\n"

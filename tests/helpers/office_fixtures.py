"""Real Office/EPUB/ODF files, stored gzipped and base64'd so the patch stays text.

Every blob here was produced by **LibreOffice**, not by the code under test.
That is the whole point and it is `B102`'s rule: a fixture written by the same
person who wrote the reader agrees with the reader's assumptions rather than
with what Word, Excel, PowerPoint and Calibre actually emit, so it passes for
the wrong reason. Driving a real file is the only way a register test says
anything (`Law 20`).

**One home, because there were two.** The `.doc` blobs lived in
``tests/test_attachment_extension_registers.py`` for `B102` and `B240` needed
real files of six more formats; a second pile of base64 in a second test file is
the thing `Law 14` is about, so the pile moved here and the registers test
imports it. The byte offsets that test pins (``_PIECE_STREAM_OFFSET`` and
friends) stay with the test that asserts them — they are statements about the
`.doc` fixture, not part of it.

**Size.** An OOXML/ODF file is a zip, and a deflated zip does not gzip; the six
zip-shaped fixtures are therefore re-stored with ``ZIP_STORED`` before gzipping,
which is a lossless repack — every part is byte-for-byte what LibreOffice wrote,
in the same order, and every reader in the world opens a stored zip. That takes
the seven fixtures from ~85 KB of base64 to ~29 KB.

The document behind the six `B240` fixtures says the same thing in each format
so one assertion works across all of them: a *Quarterly Report* heading,
``OFFICE_SENTINEL``, and a line of prose. ``rich.docx`` additionally carries a
sub-heading, a two-item list and a two-column table, because `B240`'s second
`Verify` clause is that one `.docx` renders the same whichever door it came
through and a document with no structure cannot show that.
"""

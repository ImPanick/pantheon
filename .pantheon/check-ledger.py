"""Verify `LEDGER.md` against `.pantheon/ledger/claims.py`, and render it on request.

`P19-01`. The owner asked for an evidence trail proving Pantheon is a better
Odysseus. The first design question was not *what goes in it* but *what stops it
being false in a week*, because this file's whole value is that a stranger can
check it.

**A HAND-WRITTEN LEDGER IS THE SECOND PLACE EVERY FACT ALREADY LIVES.**

`.pantheon/ROADMAP.md` records what was done and what verifies it. `CHANGELOG.md`
records what changed, because AGPL-3.0 §5(a) requires it. A third file restating
those numbers in marketing voice is `Law 13` — and it is the copy shown to
strangers, so it is the worst one to let drift.

So the ledger is generated, and `--check` fails when the file in the tree is not
what this script produces. Editing `LEDGER.md` by hand breaks CI on the next run,
which is the only reliable way to stop somebody doing it.

**WHAT `--check` ACTUALLY VERIFIES**, beyond staleness — each of these is a way a
proof ledger goes quietly wrong:

  * a claim citing a file that no longer exists (the claim outlived its evidence)
  * a claim citing a roadmap row or decision that was never written
  * a provenance tag outside the five (an unranked claim reads as a ranked one)
  * an `after` with no `before` — an assertion wearing a measurement's clothes
  * the retrieval rows losing their `fixture` tag, which is the specific
    honesty this ledger would most like to lose
  * **the stated distance behind upstream having drifted**, checked against a
    live `git rev-list` on any checkout that has the `upstream` remote
  * **the README disagreeing with either of them.** The README is the front door
    and it restates two figures: the test count on its badge and the tracked/done
    line. Both had already rotted once — the badge read `6,301 passing` against a
    suite of 8,642, and the status line said 296 tracked / 77 done against a
    tracker saying 376 / 170. A stale number on the front page of a repository
    whose whole pitch is *our numbers are checkable* is the worst possible place
    for one, so they are pinned here rather than trusted to a future editor.

**VERIFYING IS THE DEFAULT AND WRITING TAKES A FLAG**, which is not a style
choice. `release-gate.py` discovers `.pantheon/check-*.py` and runs any checker
CI does not declare with **no arguments at all** — so a script in this directory
that writes when called bare would silently rewrite a tracked file in the middle
of a gate run, and the gate would pass because it did.

Usage:
    python3 .pantheon/check-ledger.py            # verify; writes nothing
    python3 .pantheon/check-ledger.py --write    # regenerate LEDGER.md
"""
from __future__ import annotations

import argparse
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / ".pantheon"))

from ledger import claims as C  # noqa: E402

OUTPUT = ROOT / "LEDGER.md"
TRACKER = ROOT / ".pantheon" / "ROADMAP.md"
README = ROOT / "README.md"
DECISIONS = ROOT / ".pantheon" / "DECISIONS.md"

# The retrieval numbers are the ones a reader is most likely to quote and the
# ones measured on a harness fixture. If either ever loses its tag, the ledger
# starts making a claim about the product that its own corpus refuses to support.
MUST_BE_FIXTURE = ("retrieval-recall", "retrieval-mrr")

BANNER = "<!-- GENERATED by .pantheon/check-ledger.py from .pantheon/ledger/claims.py. Do not edit. -->"


def _rows_index() -> set:
    """Every row id and decision id this repo has actually written.

    Read as text rather than parsed: a row id is a row id whether it sits in a
    heading, a `Depends:` clause or a sentence, and the only question here is
    whether the ledger is citing something that exists.
    """
    text = ""
    for path in (TRACKER, DECISIONS):
        if path.exists():
            text += path.read_text(encoding="utf-8")
    return set(text.split())


def _upstream_gap_problems() -> list:
    """Check the behind-by-N claim against a live `git rev-list`, where one is possible.

    `P19-05` asked for this number to be *measured, not typed*. It cannot always
    be: the `upstream` remote lives on the deployment box, and the cloud mirror's
    history begins at an import commit. So this verifies where it can and says
    plainly that it could not where it cannot — which is the honest shape for a
    check that depends on something not every checkout has.

    **Silence would be the defect here.** A rule that quietly passes when it
    cannot run is indistinguishable from a rule that ran and agreed, and this
    particular number is the one the ledger uses to admit a weakness. A stale
    *12 behind* that has drifted to 40 makes the limitations section read as
    thorough while being wrong.
    """
    by_id = {c.id: c for c in C.CLAIMS}
    claim = by_id.get("behind-upstream")
    if claim is None:
        return ["the behind-upstream claim is gone — the ledger no longer states the gap"]
    # `git cherry`, not `git rev-list`. **This distinction was found by this
    # check failing**, which is the only reason it is right now.
    #
    # `rev-list FORK..upstream` counts commits upstream has that are not
    # reachable from the fork point — and cherry-picking does not change that,
    # because a cherry-pick is a NEW commit with a new sha. After landing five
    # upstream fixes the naive count still said 12, so the ledger would have
    # been forced to keep claiming a gap it had just closed.
    #
    # `git cherry` compares **patch ids**, so a cherry-picked fix registers as
    # `-` (we have an equivalent) and only genuinely absent work counts as `+`.
    try:
        proc = subprocess.run(
            ["git", "cherry", "main", C.UPSTREAM_REF],
            cwd=str(ROOT), capture_output=True, text=True, timeout=60,
        )
    except (OSError, subprocess.SubprocessError):
        return []
    if proc.returncode != 0:
        # No upstream remote here. Not a failure — most checkouts are like this.
        return []
    live = str(sum(1 for line in proc.stdout.splitlines() if line.startswith("+")))
    stated = re.match(r"(\d+)", claim.after.strip())
    if stated is None:
        return ["behind-upstream: the `after` no longer starts with a count"]
    if stated.group(1) != live:
        return [
            f"behind-upstream says {stated.group(1)} and `git cherry main "
            f"{C.UPSTREAM_REF}` says {live} — upstream moved"
        ]
    return []


def _checker_count_problems() -> list:
    """The checker count, against the file the gate actually reads.

    `B59`. This claim said **fifteen** while `ci.yml` listed seventeen — it had
    drifted twice without anybody noticing, because the number lives in prose
    and nothing compared it to the list. That is the same shape as the README
    figures two functions down, and the same fix: the ledger's own arithmetic
    is the first thing a sceptic checks, so it is the last thing that should be
    typed from memory.

    Counted from `ci.yml` rather than from the gate, because the gate reads
    `ci.yml` too and a check that consults the same derived value twice proves
    only that the derivation is deterministic.
    """
    by_id = {c.id: c for c in C.CLAIMS}
    claim = by_id.get("checkers")
    if claim is None:
        return ["the checkers claim is gone — the ledger no longer states the count"]
    try:
        ci = (ROOT / ".github" / "workflows" / "ci.yml").read_text(encoding="utf-8")
    except OSError:
        return []
    live = len(re.findall(r"^\s*- name: check-[\w-]+\s*$", ci, re.M))
    if not live:
        return []
    stated = re.match(r"(\d+)", claim.after.strip())
    if stated is None:
        return ["checkers: the `after` no longer starts with a count"]
    if int(stated.group(1)) != live:
        return [
            f"checkers says {stated.group(1)} and `ci.yml` lists {live} "
            f"`- name: check-*` steps"
        ]
    return []


def _readme_problems() -> list:
    """The two figures the README restates, checked against their sources.

    The README cannot be generated — it is prose, and a templated front page
    reads like one. So the numbers in it are pinned instead: change the suite or
    the tracker without changing the README and this fails, which is the same
    bargain `check-tracker.py` already makes with the progress entries.
    """
    problems = []
    if not README.exists():
        return ["README.md is missing"]
    readme = README.read_text(encoding="utf-8")

    by_id = {c.id: c for c in C.CLAIMS}
    tests = by_id.get("tests")
    if tests is not None:
        # "920 test files · 8,642 passing" -> the passing count is what the badge shows.
        passing = tests.after.split("·")[-1].strip().split()[0]
        if f"tests-{passing.replace(',', '%2C')}%20passing" not in readme:
            problems.append(
                f"README badge does not read {passing} passing, which is what the "
                f"ledger's 'tests' claim says"
            )
        if f"**{passing} passing**" not in readme:
            problems.append(f"README status line does not state {passing} passing")

    if TRACKER.exists():
        for line in TRACKER.read_text(encoding="utf-8").splitlines():
            if line.startswith("| **Total**"):
                cells = [c.strip().strip("*") for c in line.split("|")]
                tracked, done = cells[3], cells[6]
                if f"**{tracked} tracked tasks, {done} done" not in readme:
                    problems.append(
                        f"README says something other than '{tracked} tracked tasks, "
                        f"{done} done' — the tracker's Total row moved"
                    )
                break
    return problems


def verify() -> list:
    """Every way a claim can be wrong that a script can see. Returns problems."""
    problems = []
    seen = set()
    areas = {name for name, _ in C.AREAS}
    corpus = _rows_index()

    for claim in C.CLAIMS:
        where = f"{claim.id}"
        if claim.id in seen:
            problems.append(f"{where}: two claims share this id")
        seen.add(claim.id)

        if claim.area not in areas:
            problems.append(f"{where}: area {claim.area!r} is not in AREAS")

        if claim.provenance not in C.PROVENANCE:
            problems.append(
                f"{where}: provenance {claim.provenance!r} is not one of {C.PROVENANCE}"
            )

        if not claim.repro.strip():
            problems.append(f"{where}: no reproduction command — 'trust us' is not evidence")

        # A lone `after` is the shape this rule exists to catch: a number with
        # nothing to compare it to reads as an improvement and is not one.
        has_before, has_after = bool(claim.before.strip()), bool(claim.after.strip())
        if has_after != has_before:
            problems.append(
                f"{where}: has {'after' if has_after else 'before'} but not the other — "
                f"a one-sided measurement is an assertion"
            )

        for path in claim.evidence:
            if not (ROOT / path).exists():
                problems.append(f"{where}: cites {path}, which does not exist")

        for row in claim.rows:
            # Row ids appear in prose wrapped in backticks, bold, or bare.
            if not any(row in token for token in corpus):
                problems.append(
                    f"{where}: cites {row}, which is in neither ROADMAP.md nor DECISIONS.md"
                )

        if not claim.how.strip():
            problems.append(f"{where}: no 'how' — the method is the part worth reading")

    by_id = {c.id: c for c in C.CLAIMS}
    for cid in MUST_BE_FIXTURE:
        claim = by_id.get(cid)
        if claim is None:
            problems.append(f"{cid}: expected to exist and carry the fixture tag; it is gone")
        elif claim.provenance != "fixture":
            problems.append(
                f"{cid}: provenance is {claim.provenance!r} and must be 'fixture' — "
                f"the corpus declares itself a harness and the ledger must say so"
            )

    problems.extend(_readme_problems())
    problems.extend(_upstream_gap_problems())
    problems.extend(_checker_count_problems())

    if not any(c.provenance == "diffed" for c in C.CLAIMS):
        problems.append(
            "no claim is tagged 'diffed' — without one, nothing here is measured "
            "against upstream's actual tree"
        )
    return problems


def _table(rows) -> str:
    out = ["| Measure | Odysseus | Pantheon | Provenance |", "| --- | --- | --- | --- |"]
    for c in rows:
        if not c.before.strip():
            continue
        out.append(f"| {c.headline} | `{c.before}` | **`{c.after}`** | `{c.provenance}` |")
    return "\n".join(out)


def render() -> str:
    p = []
    a = p.append
    a(BANNER)
    a("")
    a("# Pantheon — the proof ledger")
    a("")
    a(f"> A fork of **Odysseus** (`{C.UPSTREAM_REMOTE}`, AGPL-3.0-or-later).")
    a(f"> Fork point `{C.FORK_POINT}`, {C.FORK_POINT_DATE} — *{C.FORK_POINT_SUBJECT}*.")
    a(f"> Every figure below measured {C.MEASURED_ON}.")
    a("")
    a("**This file is generated.** It is rendered from `.pantheon/ledger/claims.py` by")
    a("`.pantheon/check-ledger.py`, and CI fails if the two disagree. Edit the claims,")
    a("not this file.")
    a("")
    a("## How to read a row")
    a("")
    a("A ledger is worth exactly what its weakest number is worth. One figure that does")
    a("not survive being checked is not one bad row — it is the row a sceptic quotes, and")
    a("everything above and below it then reads as the same kind of thing. So every claim")
    a("here names **where its number came from** and **a command you can run**. Some of")
    a("these numbers are weaker than others; the tag says which.")
    a("")
    for tag in C.PROVENANCE:
        a(f"- **`{tag}`** — {C.PROVENANCE_MEANS[tag]}")
    a("")
    a("If you only check one thing, check a `fixture` row against its own corpus. Those")
    a("are the numbers most likely to be quoted and least able to carry the weight.")
    a("")
    a("## At a glance")
    a("")
    a(_table(C.CLAIMS))
    a("")
    a("---")
    a("")

    for name, blurb in C.AREAS:
        rows = [c for c in C.CLAIMS if c.area == name]
        if not rows:
            continue
        a(f"## {name}")
        a("")
        a(f"*{blurb}*")
        a("")
        for c in rows:
            a(f"### {c.headline}")
            a("")
            if c.before.strip():
                a(f"**`{c.before}` → `{c.after}`**  ·  provenance **`{c.provenance}`**")
            else:
                a(f"provenance **`{c.provenance}`**")
            a("")
            a(f"**Odysseus:** {c.stock}")
            a("")
            a(f"**Pantheon:** {c.pantheon}")
            a("")
            a(f"**How we got there.** {c.how}")
            a("")
            a("```")
            a(c.repro)
            a("```")
            if c.rows:
                a("")
                a("Argued in: " + ", ".join(f"`{r}`" for r in c.rows) + ".")
            a("")
        a("---")
        a("")

    a("## What this ledger does not prove")
    a("")
    a("Stated here rather than left for a reader to find, because a ledger with no")
    a("limitations section reads as marketing.")
    a("")
    a("1. **The retrieval numbers are measured on a harness fixture.** They prove the")
    a("   scorer works and that two engines were compared over one corpus. They are not")
    a("   a measurement of how well Pantheon remembers in daily use, and no number in")
    a("   this repository is. Building one takes an operator's own memories and probes")
    a("   they wrote themselves: `.pantheon/retrieval_eval.py --generate`.")
    a("2. **Seven upstream commits are unmerged** — documentation restructuring and")
    a("   dependency bumps, deliberately declined. The five real fixes were")
    a("   cherry-picked on 2026-09-12 (`P19-06`) and the two that were a security")
    a("   advisory were backported ahead of them (`B70`). Measuring this gap is what")
    a("   found them: a bearer API token had inherited its minting admin's tool")
    a("   authority, and an approval grant was readable out of caller-writable message")
    a("   metadata. **A fork that stops taking upstream's fixes does not merely go")
    a("   stale.**")
    a("3. **Most rows compare code, not outcomes.** *Fewer unreachable handlers* and")
    a("   *every silent failure explained* are real and checkable; neither is a")
    a("   measurement of a person getting their work done faster.")
    a("4. **Most rows here are about this fork's own tree.** The suite is green —")
    a("   8,819 passing, nothing red, after 14 standing failures were cleared on")
    a("   2026-09-12 — but a green suite is evidence about the code under it, not")
    a("   about a deployment. `P10-10`'s manual pass over every surface is still")
    a("   not done, and no automated check substitutes for it.")
    a("")
    a("## Reproducing all of it")
    a("")
    a("```")
    a("python3 .pantheon/release-gate.py        # all 15 checkers plus the suite")
    a("python3 .pantheon/retrieval_eval.py      # the memory numbers, with their caveat")
    a("python3 .pantheon/check-ledger.py          # this file, verified")
    a("```")
    a("")
    a("The `diffed` rows need the upstream remote:")
    a("")
    a("```")
    a(f"git remote add upstream https://github.com/{C.UPSTREAM_REMOTE}.git")
    a("git fetch upstream")
    a(f"git diff --shortstat {C.FORK_POINT}..HEAD")
    a("```")
    a("")
    return "\n".join(p) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--write", action="store_true",
                    help="regenerate LEDGER.md (default is to verify and write nothing)")
    args = ap.parse_args()

    problems = verify()
    rendered = render()

    if not args.write:
        if not OUTPUT.exists():
            problems.append("LEDGER.md does not exist — run with --write to create it")
        elif OUTPUT.read_text(encoding="utf-8") != rendered:
            problems.append(
                "LEDGER.md is stale or was hand-edited — run "
                "`python3 .pantheon/check-ledger.py --write` and commit the result"
            )
        if problems:
            print(f"ledger FAILED — {len(problems)} problem(s)\n")
            for p in problems:
                print(f"  {p}")
            return 1
        fixture = sum(1 for c in C.CLAIMS if c.provenance == "fixture")
        print(
            f"ledger OK — {len(C.CLAIMS)} claims across {len(C.AREAS)} areas, "
            f"{fixture} labelled fixture, every cited path present"
        )
        return 0

    if problems:
        print(f"ledger FAILED — {len(problems)} problem(s), nothing written\n")
        for p in problems:
            print(f"  {p}")
        return 1
    OUTPUT.write_text(rendered, encoding="utf-8")
    print(f"wrote {OUTPUT.relative_to(ROOT)} — {len(C.CLAIMS)} claims")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
